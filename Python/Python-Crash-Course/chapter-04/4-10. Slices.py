players = ['charles', 'martina', 'michael', 'florence', 'eli']

# 1. Primeros tres
print("The first three items in the list are:")
print(players[:3])

# 2. Tres del medio
print("Three items from the middle of the list are:")
print(players[1:4])

# 3. Últimos tres
print("The last three items in the list are:")
print(players[-3:])